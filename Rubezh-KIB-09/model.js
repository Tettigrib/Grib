function validAnswer(value){return Number.isInteger(value)&&value>=0&&value<4}
function fresh(){return {answers:Array(18).fill(null),selected:[],budget:6,profile:0}}
function clean(input){
 const result=fresh();
 if(!input || typeof input!=='object')return result;
 if(Array.isArray(input.answers))result.answers=result.answers.map((_,i)=>validAnswer(input.answers[i])?input.answers[i]:null);
 if(Number.isInteger(input.profile)&&profiles[input.profile])result.profile=input.profile;
 if([3,6,10].includes(input.budget))result.budget=input.budget;
 if(Array.isArray(input.selected))for(const i of new Set(input.selected)){
  if(Number.isInteger(i)&&controls[i]&&result.answers[i]!==2&&validAnswer(result.answers[i])&&effort(result)+controls[i][3]<=result.budget)result.selected.push(i)
 }
 return result
}
function points(a){return a===2?2:a===1?1:0}
function effort(s){return s.selected.reduce((sum,i)=>sum+controls[i][3],0)}
function score(answers){return Math.round(answers.reduce((n,a)=>n+points(a),0)*100/(answers.length*2))}
function complete(s){return s.answers.every(validAnswer)}
function forecast(s){return score(s.answers.map((a,i)=>s.selected.includes(i)?2:a))}
function gaps(s){return controls.map((_,i)=>i).filter(i=>validAnswer(s.answers[i])&&s.answers[i]!==2).sort((a,b)=>points(s.answers[a])-points(s.answers[b])||controls[a][3]-controls[b][3]||a-b)}
